# tipo de variavel que só comporta True ou False
# verdadeiro ou falso
# usado para comparações no geral
# se é ou não é


if True:
    print("bloco if aparece")
else:
    print("bloco else aparece")
#   bloco if aparece
# nesse caso, como sempre começa com True, o bloco do if será executado


# operadores lógicos
# and
if True and True:
    print("bloco com and será executado")
    # bloco com and será executado
# necessita que duas condições sejam verdadeiras para ser executado!!!

# or
if True or False:
    print("bloco com or sera executado")
    # bloco com or sera executado
# necessita que apenas uma das condições seja True!