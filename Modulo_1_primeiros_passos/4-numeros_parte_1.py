# python tem vários tipos de números

# inteiro
numero_inteiro = 3
# numero cheio sem ponto

# real com ponto flutuante
numero_real = 3.14
# numero com virgula
# trbalho com dinheiro é essencial que se use o real com ponto flutuante

print("inteiro =", numero_inteiro)
# inteiro = 3


print("real =", numero_real)
# real = 3.14
# =========================================


# função type()
# mostra o tipo da variável
print("Esse é o tipo do número que estamos trabalhando: ", type(numero_real))
# Esse é o tipo do número que estamos trabalhando:  <class 'float'>
print("Esse é o tipo do número que estamos trabalhando: ", type(numero_inteiro))
# Esse é o tipo do número que estamos trabalhando:  <class 'int'>